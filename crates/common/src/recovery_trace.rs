//! Source evidence shared by native dispatch capture and historical callbacks.
//!
//! Serialized records describe the source. They do not establish a current node phase,
//! prove a successful replay or authorize a venue command.

use anyhow::{Context, Result, ensure};
use nautilus_core::UUID4;
use serde::{Deserialize, Serialize};
use serde_json::Value;

/// A source family generated by an actual native dispatch producer.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum NativeInputSource {
    Time,
    SystemEvent,
    SystemCommand,
    ExecutionEvent,
    TradingCommand,
    DataEvent,
    DataCommand,
    ExternalMessage,
    QueryResult,
    Maintenance,
    Lifecycle,
    Reconciliation,
}

/// The immutable source installation and codec contract.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeTraceSource {
    pub schema_version: u32,
    pub node_instance: UUID4,
    pub process_incarnation: UUID4,
    pub journal_run: String,
    pub logical_run: String,
    pub configuration_digest: String,
    pub codec_profile: String,
    pub registered_profile_digest: String,
}

impl NativeTraceSource {
    /// Validates the versioned source identity without issuing runtime authority.
    ///
    /// # Errors
    /// Refuses absent, oversized or unsupported identities.
    pub fn validate(&self) -> Result<()> {
        ensure!(
            self.schema_version == 1,
            "unsupported native trace source schema"
        );
        for value in [
            &self.journal_run,
            &self.logical_run,
            &self.configuration_digest,
            &self.codec_profile,
            &self.registered_profile_digest,
        ] {
            ensure!(
                !value.is_empty() && value.len() <= 256 && !value.contains('\0'),
                "invalid native trace source identity"
            );
        }
        Ok(())
    }
}

