#[cfg(feature = "live")]
pub mod scope {
    use std::{cell::RefCell, marker::PhantomData, rc::Rc};

    use anyhow::{Context, Result, ensure};

    use super::{
        NativeCallbackRoute, NativeIngressReceipt, NativeInputCause, NativeInputSource,
        NativeOutputOrigin, NativeTraceSource,
    };
    use crate::live::dst;

    #[derive(Debug)]
    struct Frame {
        epoch: u64,
        source: NativeTraceSource,
        root: u64,
        input: u64,
        parent: Option<u64>,
        output_count: u64,
        activity_at: dst::time::Instant,
        callbacks: Vec<NativeCallbackRoute>,
        transports: Vec<super::NativeTransportReceipt>,
        uuid_draws: Vec<nautilus_core::UUID4>,
        clock_reads: Vec<super::NativeClockRead>,
        queued_outputs: Vec<super::NativeQueuedOutput>,
        read_views: super::NativeReadBindings,
    }

    #[derive(Debug, Default)]
    struct State {
        next_epoch: u64,
        frames: Vec<Frame>,
        failed: bool,
        receipts_enabled: bool,
        received: Option<NativeIngressReceipt>,
    }

    thread_local! {
        static CURRENT: RefCell<State> = RefCell::new(State::default());
    }

    pub(crate) fn fail() {
        CURRENT.with(|current| {
            if let Ok(mut state) = current.try_borrow_mut() {
                state.failed = true;
            }
        });
    }
    pub(crate) fn note_queued_output(output: super::NativeQueuedOutput) -> Result<()> {
        CURRENT.with(|current| {
            let mut state = current
                .try_borrow_mut()
                .context("native queue capture reentered")?;
            ensure!(!state.failed, "native queue source failed");
            let frame = state
                .frames
                .last_mut()
                .context("native queue source frame absent")?;
            ensure!(
                output.receipt.caused_by
                    == Some(NativeInputCause {
                        process_incarnation: frame.source.process_incarnation,
                        journal_run: frame.source.journal_run.clone(),
                        root_sequence: frame.root,
                        input_sequence: frame.input
                    }),
                "native derived queue cause changed"
            );
            frame.queued_outputs.push(output);
            Ok(())
        })
    }

    /// Records the actual callback route on the active source scope, if any.
    /// This does not invoke a handler or grant callback admission.
    /// # Errors
    /// Refuses a failed source or empty identity.
    pub fn note_callback(route: NativeCallbackRoute) -> Result<()> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native callback scope reentered")?;
            ensure!(!state.failed, "native source callback scope failed");
            ensure!(
                !route.component_id.is_empty() && !route.kind.is_empty(),
                "native callback identity absent"
            );
            if let Some(frame) = state.frames.last_mut() {
                frame.callbacks.push(route);
            }
            Ok(())
        })
    }

    #[must_use]
    pub(crate) fn capture_active() -> bool {
        CURRENT
            .try_with(|state| {
                state
                    .try_borrow()
                    .map_or(true, |state| !state.frames.is_empty())
            })
            .unwrap_or(true)
    }

    pub(super) fn note_uuid(uuid: nautilus_core::UUID4) -> Result<()> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native UUID scope reentered")?;
            ensure!(!state.failed, "native UUID scope failed");
            if let Some(frame) = state.frames.last_mut() {
                frame.uuid_draws.push(uuid);
            }
            Ok(())
        })
    }
    pub(super) fn note_transport(receipt: super::NativeTransportReceipt) -> Result<()> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native transport scope reentered")?;
            ensure!(!state.failed, "native transport scope failed");
            if let Some(frame) = state.frames.last_mut() {
                frame.transports.push(receipt);
            }
            Ok(())
        })
    }

    pub(super) fn note_clock_read(read: super::NativeClockRead) -> Result<()> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native Clock source reentered")?;
            ensure!(!state.failed, "native Clock source failed");
            if let Some(frame) = state.frames.last_mut() {
                frame.clock_reads.push(read);
            }
            Ok(())
        })
    }

    /// Reads only the innermost actual input's matching opaque producer capture.
    /// Outside native capture it returns `None`; it never falls back to a parent input.
    ///
    /// # Errors
    /// Refuses failed/reentered capture, an unbound producer or a different value type.
    pub fn current_read_view<T: std::any::Any + Send + Sync>(
        producer: &super::NativeReadProducerToken,
    ) -> Result<Option<super::NativeReadView<T>>> {
        CURRENT.with(|current| {
            let state = current
                .try_borrow()
                .context("native read source reentered")?;
            let Some(frame) = state.frames.last() else {
                return Ok(None);
            };
            ensure!(!state.failed, "native read source failed");
            let binding = frame
                .read_views
                .0
                .iter()
                .find(|binding| std::sync::Arc::ptr_eq(&binding.producer.0, &producer.0))
                .context("native read producer is not bound to current input")?;
            let value = binding
                .value
                .clone()
                .downcast::<T>()
                .map_err(|_| anyhow::anyhow!("native read producer value type changed"))?;
            Ok(Some(super::NativeReadView {
                witness: binding.witness.clone(),
                value,
            }))
        })
    }

    /// Enables receipt tracking before the owning node starts consuming its channels.
    /// This records source admission and does not change callback or venue permissions.
    ///
    /// # Errors
    /// Refuses an already active, failed or previously consumed receipt scope.
    pub fn enable_ingress_receipts() -> Result<()> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native receipt scope reentered")?;
            ensure!(
                !state.failed && !state.receipts_enabled && state.frames.is_empty(),
                "native receipt scope unavailable"
            );
            state.receipts_enabled = true;
            Ok(())
        })
    }

    /// Records the receipt physically dequeued with the actual message.
    /// Overwriting an unconsumed receipt poisons the source instead of dropping identity.
    pub fn received_ingress(receipt: Option<NativeIngressReceipt>) {
        let _ = CURRENT.try_with(|state| {
            if let Ok(mut state) = state.try_borrow_mut() {
                if !state.receipts_enabled {
                    return;
                }
                if state.received.is_some() || receipt.is_none() {
                    state.failed = true;
                }
                state.received = receipt;
            }
        });
    }

    /// Consumes only the receipt for this actual native producer.
    /// Inline mutation producers have no channel receipt and retain their real processing sample.
    ///
    /// # Errors
    /// Refuses a foreign channel, missing runner receipt, overwritten evidence or reentrancy.
    pub fn take_ingress(source: NativeInputSource) -> Result<Option<NativeIngressReceipt>> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native receipt scope reentered")?;
            ensure!(!state.failed, "native receipt scope failed");
            let runner_source = matches!(
                source,
                NativeInputSource::Time
                    | NativeInputSource::SystemEvent
                    | NativeInputSource::SystemCommand
                    | NativeInputSource::ExecutionEvent
                    | NativeInputSource::TradingCommand
                    | NativeInputSource::DataEvent
                    | NativeInputSource::DataCommand
            );
            if runner_source && let Some(receipt) = state.received.take() {
                ensure!(
                    receipt.input_source == source,
                    "native receipt channel mismatch"
                );
                Ok(Some(receipt))
            } else {
                ensure!(
                    !runner_source || !state.frames.is_empty(),
                    "native runner input missing receipt"
                );
                ensure!(
                    state.received.is_none(),
                    "runner receipt replaced by inline producer"
                );
                Ok(None)
            }
        })
    }

    /// An owner-thread native capture scope. It carries no submission permission.
    #[derive(Debug)]
    pub struct NativeCaptureScope {
        epoch: u64,
        finished: bool,
        owner: PhantomData<Rc<()>>,
    }

    impl NativeCaptureScope {
        /// Binds the acknowledged native input to synchronous output capture.
        ///
        /// # Errors
        /// Refuses inconsistent nesting, a foreign source or a failed scope.
        pub fn enter(
            source: &NativeTraceSource,
            root: u64,
            input: u64,
            parent: Option<u64>,
            activity_at: dst::time::Instant,
        ) -> Result<Self> {
            Self::enter_with_read_views(
                source,
                root,
                input,
                parent,
                activity_at,
                super::NativeReadBindings::default(),
            )
        }

        /// Binds the exact process-local reads after the owning Begin was acknowledged.
        ///
        /// # Errors
        /// Refuses the same failed, foreign or inconsistent scope as `enter`.
        pub fn enter_with_read_views(
            source: &NativeTraceSource,
            root: u64,
            input: u64,
            parent: Option<u64>,
            activity_at: dst::time::Instant,
            read_views: super::NativeReadBindings,
        ) -> Result<Self> {
            source.validate()?;
            ensure!(root > 0 && input > 0, "invalid native scope frontier");
            CURRENT.with(|state| {
                let mut state = state
                    .try_borrow_mut()
                    .context("native capture scope reentered")?;
                ensure!(!state.failed, "native capture scope failed");
                match state.frames.last() {
                    Some(previous) => ensure!(
                        previous.source == *source
                            && previous.root == root
                            && Some(previous.input) == parent,
                        "native capture nesting mismatch"
                    ),
                    None => ensure!(parent.is_none(), "native capture missing stack parent"),
                }
                state.next_epoch = state
                    .next_epoch
                    .checked_add(1)
                    .context("native scope exhausted")?;
                let epoch = state.next_epoch;
                state.frames.push(Frame {
                    epoch,
                    source: source.clone(),
                    root,
                    input,
                    parent,
                    output_count: 0,
                    activity_at,
                    callbacks: Vec::new(),
                    transports: Vec::new(),
                    uuid_draws: Vec::new(),
                    clock_reads: Vec::new(),
                    queued_outputs: Vec::new(),
                    read_views,
                });
                Ok(Self {
                    epoch,
                    finished: false,
                    owner: PhantomData,
                })
            })
        }

        /// Returns all actual Clock reads in callback and native effect capture order.
        ///
        /// # Errors
        /// Returns an error if capture is absent, reentered, failed, or belongs to another input epoch.
        pub fn clock_reads(&self) -> Result<Vec<super::NativeClockRead>> {
            CURRENT.with(|state| {
                let state = state
                    .try_borrow()
                    .context("native Clock source reentered")?;
                let frame = state.frames.last().context("native Clock source absent")?;
                ensure!(
                    !state.failed && frame.epoch == self.epoch,
                    "native Clock source changed"
                );
                Ok(frame.clock_reads.clone())
            })
        }

        /// Returns the actual number of captured outputs in this exact scope.
        ///
        /// # Errors
        /// Refuses a changed, nested, reentered or failed scope.
        /// Returns actual source native UUID decisions for this input.
        /// # Errors
        /// Refuses a changed source scope.
        pub fn uuid_draws(&self) -> Result<Vec<nautilus_core::UUID4>> {
            CURRENT.with(|state| {
                let state = state.try_borrow().context("native UUID scope reentered")?;
                let frame = state.frames.last().context("native UUID frame absent")?;
                ensure!(
                    !state.failed && frame.epoch == self.epoch,
                    "native UUID scope changed"
                );
                Ok(frame.uuid_draws.clone())
            })
        }
        ///
        /// # Errors
        /// Returns an error if queued capture is absent, reentered, failed, or belongs to another input epoch.
        pub fn queued_outputs(&self) -> Result<Vec<super::NativeQueuedOutput>> {
            CURRENT.with(|current| {
                let state = current
                    .try_borrow()
                    .context("native queued scope reentered")?;
                let frame = state.frames.last().context("native queued scope absent")?;
                ensure!(
                    !state.failed && frame.epoch == self.epoch,
                    "native queued scope changed"
                );
                Ok(frame.queued_outputs.clone())
            })
        }
        /// Returns actual immediate transport outcomes, separate from venue acceptance.
        /// # Errors
        /// Refuses a changed source scope.
        pub fn transports(&self) -> Result<Vec<super::NativeTransportReceipt>> {
            CURRENT.with(|state| {
                let state = state
                    .try_borrow()
                    .context("native transport scope reentered")?;
                let frame = state
                    .frames
                    .last()
                    .context("native transport frame absent")?;
                ensure!(
                    !state.failed && frame.epoch == self.epoch,
                    "native transport scope changed"
                );
                Ok(frame.transports.clone())
            })
        }

        /// Returns exact source callback order for this active input.
        /// # Errors
        /// Refuses a foreign, changed or failed scope.
        pub fn callbacks(&self) -> Result<Vec<NativeCallbackRoute>> {
            CURRENT.with(|state| {
                let state = state.try_borrow().context("native callbacks reentered")?;
                ensure!(!state.failed, "native callback scope failed");
                let frame = state
                    .frames
                    .last()
                    .context("native callback frame absent")?;
                ensure!(frame.epoch == self.epoch, "native callback frame changed");
                Ok(frame.callbacks.clone())
            })
        }

        ///
        /// # Errors
        /// Returns an error if capture is absent, reentered, failed, or belongs to another input epoch.
        pub fn output_count(&self) -> Result<u64> {
            CURRENT.with(|state| {
                let state = state
                    .try_borrow()
                    .context("native capture scope reentered")?;
                let frame = state.frames.last().context("native capture scope absent")?;
                ensure!(
                    !state.failed && frame.epoch == self.epoch,
                    "native capture scope changed"
                );
                Ok(frame.output_count)
            })
        }

        /// Ends only this scope after its actual durable completion acknowledgment.
        ///
        /// # Errors
        /// Refuses a stale, nested or failed scope.
        pub fn finish(mut self) -> Result<()> {
            self.output_count()?;
            CURRENT.with(|state| {
                state.borrow_mut().frames.pop();
            });
            self.finished = true;
            Ok(())
        }
    }

    impl Drop for NativeCaptureScope {
        fn drop(&mut self) {
            if !self.finished {
                let _ = CURRENT.try_with(|state| {
                    if let Ok(mut state) = state.try_borrow_mut() {
                        state.failed = true;
                        // Failed capture still releases only this guard's owned
                        // branch. Keeping a dead frame would make ordinary cleanup
                        // Clock reads attempt to append to an abandoned input.
                        // The permanent source-failure latch is never cleared.
                        if let Some(index) = state
                            .frames
                            .iter()
                            .position(|frame| frame.epoch == self.epoch)
                        {
                            state.frames.truncate(index);
                        }
                    }
                });
            }
        }
    }

    /// Returns the actual producing input for a later queued message.
    #[must_use]
    pub fn current_cause() -> Option<NativeInputCause> {
        CURRENT
            .try_with(|state| {
                state.try_borrow().ok().and_then(|state| {
                    if state.failed {
                        return None;
                    }
                    state.frames.last().map(|frame| NativeInputCause {
                        process_incarnation: frame.source.process_incarnation,
                        journal_run: frame.source.journal_run.clone(),
                        root_sequence: frame.root,
                        input_sequence: frame.input,
                    })
                })
            })
            .ok()
            .flatten()
    }

    /// Allocates correlation only at the actual native output capture point.
    ///
    /// # Errors
    /// Refuses reentrancy, overflow or a failed scope. No active scope is explicitly absent.
    pub fn next_output_origin() -> Result<Option<NativeOutputOrigin>> {
        CURRENT.with(|state| {
            let mut state = state
                .try_borrow_mut()
                .context("native output capture reentered")?;
            ensure!(!state.failed, "native output capture scope failed");
            let Some(frame) = state.frames.last_mut() else {
                return Ok(None);
            };
            frame.output_count = frame
                .output_count
                .checked_add(1)
                .context("native output ordinal exhausted")?;
            Ok(Some(NativeOutputOrigin {
                source: frame.source.clone(),
                root_sequence: frame.root,
                input_sequence: frame.input,
                stack_parent: frame.parent,
                output_ordinal: frame.output_count,
            }))
        })
    }

    /// Uses the source dispatch's private receipt for native activity bookkeeping.
    /// Real authorization and freshness clocks are unaffected.
    #[must_use]
    pub fn effective_activity_instant() -> dst::time::Instant {
        if let Some(at) = super::historical::activity_instant() {
            return at;
        }
        CURRENT
            .try_with(|state| {
                state
                    .try_borrow()
                    .ok()
                    .and_then(|state| state.frames.last().map(|frame| frame.activity_at))
            })
            .ok()
            .flatten()
            .unwrap_or_else(dst::time::Instant::now)
    }
}

