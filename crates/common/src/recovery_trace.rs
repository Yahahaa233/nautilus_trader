#[cfg(feature = "live")]
type NativeIngressEncoder = dyn Fn(NativeInputSource, &dyn std::any::Any) -> Result<Value>;
#[cfg(feature = "live")]
thread_local! { static INGRESS_ENCODER: std::cell::RefCell<Option<std::rc::Rc<NativeIngressEncoder>>> = const { std::cell::RefCell::new(None) }; }
/// Installs this actual node's strict source codec for local derived queue effects.
#[cfg(feature = "live")]
pub fn set_native_ingress_encoder(
    encode: impl Fn(NativeInputSource, &dyn std::any::Any) -> Result<Value> + 'static,
) {
    INGRESS_ENCODER.with(|current| *current.borrow_mut() = Some(std::rc::Rc::new(encode)));
}
#[cfg(feature = "live")]
pub(crate) fn encode_native_ingress(
    source: NativeInputSource,
    input: &dyn std::any::Any,
) -> Result<Value> {
    use crate::live::dispatch::DispatchMessage;

    let encode = INGRESS_ENCODER
        .with(|current| {
            current
                .try_borrow()
                .ok()
                .and_then(|current| current.clone())
        })
        .context("native derived queue codec absent or busy")?;
    // Admission envelopes carry callback ancestry, but original queue evidence
    // encodes only the unchanged domain payload.
    let input: &dyn std::any::Any = if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::messages::DataEvent>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::messages::ExecutionEvent>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::messages::SystemEvent>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::messages::SystemCommand>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::messages::data::DataCommand>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::runner::TradingCommandMessage>>()
    {
        envelope.message()
    } else if let Some(envelope) =
        input.downcast_ref::<DispatchMessage<crate::runner::TimeEventMessage>>()
    {
        envelope.message()
    } else {
        input
    };
    encode(source, input)
}

